export function renderGuide(root, { onClose }) {
  fill(root,
    h('header', { class: 'sheet__head' },
      h('h2', { id: 'guide-title' }, '사용법'),
      h('button', { type: 'button', class: 'icon-btn', 'aria-label': '닫기', onClick: onClose }, '✕')),
    h('div', { class: 'sheet__body guide', 'aria-labelledby': 'guide-title' },
      h('p', { class: 'small' }, '작근단 수송대대 병이 자기 휴가를 기록하고 출타를 계획하는 개인용 앱입니다. 기록을 자동으로 서버에 보내지 않고, 일정 공유는 직접 보낼 때만 이루어집니다. 공식 휴가 승인·판정 도구가 아니며, 최종 판단은 부대 행정 기준을 따릅니다. 영내에서는 부대 휴대폰 사용 지침을 지켜 주세요.'),
      SECTIONS.map((s) => h('section', { class: 'guide__section' },
        h('h3', { class: 'sub-title' }, s.title),
        h('ul', { class: 'rules' }, s.items.map((t) => h('li', null, t))))),
      h('p', { class: 'muted small' }, '면회외출은 복무 중 총 7회, 외출은 한 달 2회(넘어가지 않음)로 셉니다. 성과제외박만 쓰거나 정기휴가가 들어간 출타는 후급이 없습니다. 그 밖의 후급 여부와 성과제외박 사용 기한·결합은 앱이 판정하지 않습니다. 설정 → 적용 규칙에서 목록을 볼 수 있습니다.'),
      h('div', { class: 'sheet__actions' }, h('button', { type: 'button', class: 'btn btn--primary', onClick: onClose }, '닫기'))));
  return null;
}
